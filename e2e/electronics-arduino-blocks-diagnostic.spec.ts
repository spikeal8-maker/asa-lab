function expectedSource(milliseconds: number): string {
  return `// C++ code generated by ASA Lab
// Arduino Uno R3

void setup()
{
  pinMode(13, OUTPUT);
  pinMode(12, OUTPUT);
  pinMode(11, OUTPUT);
}

void loop()
{
  digitalWrite(13, HIGH);
  digitalWrite(12, HIGH);
  digitalWrite(11, HIGH);
  delay(${milliseconds});
  digitalWrite(13, LOW);
  digitalWrite(12, LOW);
  digitalWrite(11, LOW);
  delay(${milliseconds});
}
`;
}

function seededWorkspace(): string {
  const chain = [
    ...[13, 12, 11].map((pin) => ({
      type: 'asa_digital_write',
      id: `high-${pin}`,
      fields: { PIN: String(pin), LEVEL: 'HIGH' },
    })),
    { type: 'asa_wait', id: 'wait-high', fields: { TIME: 1, UNIT: 'SECONDS' } },
    ...[13, 12, 11].map((pin) => ({
      type: 'asa_digital_write',
      id: `low-${pin}`,
      fields: { PIN: String(pin), LEVEL: 'LOW' },
    })),
    { type: 'asa_wait', id: 'wait-low', fields: { TIME: 1, UNIT: 'SECONDS' } },
  ];
  let first: unknown;
  for (const block of [...chain].reverse())
    first = { ...block, ...(first ? { next: { block: first } } : {}) };
  return JSON.stringify({
    blocks: {
      languageVersion: 0,
      blocks: [
        { type: 'asa_setup', id: 'setup-owner', x: 400, y: 70 },
        { type: 'asa_loop', id: 'loop-owner', x: 400, y: 180, inputs: { DO: { block: first } } },
      ],
    },
  });
}

