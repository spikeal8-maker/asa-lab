import console from 'node:console';
import process from 'node:process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'vite';

const repositoryRoot = resolve(import.meta.dirname, '..');
const reportPath = resolve(repositoryRoot, 'reports/electronics-opt0-baseline.json');
const summaryPath = resolve(repositoryRoot, 'reports/electronics-opt0-baseline.md');
const quick = process.argv.includes('--quick');
const environment = {
  ...process.env,
  ASA_ELECTRONICS_BENCHMARK_REPORT: reportPath,
  ...(quick
    ? {
        ASA_ELECTRONICS_BENCHMARK_WARMUPS: '1',
        ASA_ELECTRONICS_BENCHMARK_ITERATIONS: '3',
        ASA_ELECTRONICS_BENCHMARK_SERIES: '1',
      }
    : {}),
};
Object.assign(process.env, environment);
const vite = await createServer({
  configFile: resolve(repositoryRoot, 'apps/web/vite.config.ts'),
  server: { middlewareMode: true },
  appType: 'custom',
});
try {
  const runnerPath = resolve(
    repositoryRoot,
    'tests/electronics/run-electronics-benchmark.ts',
  ).replaceAll('\\', '/');
  await vite.ssrLoadModule(`/@fs/${runnerPath}`);
} finally {
  await vite.close();
}
const report = JSON.parse(readFileSync(reportPath, 'utf8'));
const rows = report.cases
  .map(
    (entry) =>
      `| ${entry.caseId} | ${entry.tier} | ${entry.category} | ${entry.status} | ${entry.p50Ms.toFixed(3)} | ${entry.p95Ms.toFixed(3)} | ${entry.p99Ms.toFixed(3)} | ${entry.maxMs.toFixed(3)} | ${entry.heapDeltaBytes} |`,
  )
  .join('\n');
const slowest = [...report.cases].sort((left, right) => right.p95Ms - left.p95Ms).slice(0, 5);
const markdown = `# ASA Lab Electronics E-OPT-0 baseline

Generated by \`pnpm benchmark:electronics\`. This is a measurement receipt only.
It does not change solver equations, Arduino semantics, production data or deployment.

## Receipt

- revision: \`${report.revision}\`
- dirty tree before generation: \`${report.dirtyTree}\`
- corpus: \`${report.corpusVersion}\`
- runtime: \`${report.runtime}\`
- environment: \`${report.os}\`
- CPU: \`${report.cpu}\` (${report.logicalCpuCount} logical CPUs)
- total memory: ${(report.totalMemoryBytes / 2 ** 30).toFixed(1)} GiB
- protocol: ${report.warmups} warmups, ${report.iterations} iterations, ${report.seriesCount} series
- memory: ${report.memoryMethod}
- browser long tasks: ${report.longTaskMethod}

## Slowest p95 cases

${slowest.map((entry, index) => `${index + 1}. \`${entry.caseId}\` - ${entry.p95Ms.toFixed(3)} ms`).join('\n')}
`;
const completedMarkdown = `${markdown}

## Cases

| Case | Tier | Category | Status | p50 ms | p95 ms | p99 ms | max ms | heap delta B |
| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: |
${rows}

## Interpretation boundary

This receipt measures domain execution in Node/Vite on one machine and one exact SHA.
It is the before-state for E-OPT. It is not browser responsiveness evidence and does
not by itself justify a Worker migration. Browser main-thread long tasks, Worker
transfer overhead and route load remain separate E-OPT-0/E-OPT-1 evidence.

All cases must keep the expected status and deterministic fingerprint. A performance
change that breaks those invariants is a regression, not an optimization.
`;
writeFileSync(summaryPath, completedMarkdown, 'utf8');
console.log(`Wrote ${reportPath}`);
console.log(`Wrote ${summaryPath}`);
