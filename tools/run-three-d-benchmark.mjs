import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'vite';

const repositoryRoot = resolve(import.meta.dirname, '..');
const reportPath = resolve(repositoryRoot, 'reports/three-d-baseline.json');
const summaryPath = resolve(repositoryRoot, 'docs/delivery/THREE_D_OPT_0_BASELINE.md');
const quick = process.argv.includes('--quick');
const environment = {
  ...process.env,
  ASA_3D_BENCHMARK_REPORT: reportPath,
  ...(quick
    ? {
        ASA_3D_BENCHMARK_WARMUPS: '1',
        ASA_3D_BENCHMARK_ITERATIONS: '3',
        ASA_3D_BENCHMARK_SERIES: '1',
      }
    : {}),
};
Object.assign(process.env, environment);
const vite = await createServer({
  configFile: resolve(repositoryRoot, 'apps/web/vite.config.ts'),
  server: { middlewareMode: true },
  appType: 'custom',
});
try {
  const runnerPath = resolve(repositoryRoot, 'tests/three-d/run-geometry-benchmark.ts').replaceAll(
    '\\',
    '/',
  );
  await vite.ssrLoadModule(`/@fs/${runnerPath}`);
} finally {
  await vite.close();
}

const report = JSON.parse(readFileSync(reportPath, 'utf8'));
const rows = report.cases
  .map((entry) => {
    const diagnostics =
      entry.diagnosticCodes.length > 0 ? entry.diagnosticCodes.join(', ') : 'none';
    return `| ${entry.caseId} | ${entry.tier} | ${entry.resultKind} | ${diagnostics} | ${entry.triangleCount} | ${entry.p95Ms.toFixed(3)} | ${entry.maxMs.toFixed(3)} | ${entry.checksum ?? 'none'} |`;
  })
  .join('\n');
const knownFailures = report.cases.filter(
  (entry) => entry.expectation.kind === 'known-legacy-failure',
).length;
const validationRejections = report.cases.filter(
  (entry) => entry.resultKind === 'validation-rejection',
).length;
const engineExceptions = report.cases.filter(
  (entry) => entry.resultKind === 'engine-exception',
).length;
const markdown = `# ASA 3D OPT-0 baseline

Generated by \`pnpm benchmark:three-d\`. This receipt measures the current legacy
BSP; it does not approve a replacement engine or change runtime behaviour.

## Receipt

- revision: \`${report.revision}\`
- dirty tree before report generation: \`${report.dirtyTree}\`
- engine: \`${report.engineVersion}\`
- corpus/schema: \`${report.corpusVersion}/${report.schemaVersion}\`
- runtime: \`${report.runtime}\`
- environment: \`${report.os}\`
- CPU: \`${report.cpu}\`
- protocol: ${report.warmups} warmups, ${report.iterations} iterations, ${report.seriesCount} series
- memory method: ${report.memoryMethod}
- long-task method: ${report.longTaskMethod}
- known legacy expectations: ${knownFailures}
- measured validation rejections: ${validationRejections}
- engine exceptions: ${engineExceptions}

## Cases

| Case | Tier | Result | Diagnostics | Triangles | p95 ms | max ms | Checksum |
| --- | --- | --- | --- | ---: | ---: | ---: | --- |
${rows}

## Interpretation boundary

Node timings compare geometry work on this receipt only. They are not browser UI
responsiveness evidence. Final performance budgets, Worker transfer cost and
browser long tasks remain decisions for OPT-1 after this baseline is reviewed.
`;
writeFileSync(summaryPath, markdown, 'utf8');
console.log(`Wrote ${reportPath}`);
console.log(`Wrote ${summaryPath}`);
