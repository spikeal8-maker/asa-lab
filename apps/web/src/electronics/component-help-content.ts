import type { ComponentKind } from '../api';
import { ordinaryLedProfile } from '@asa-lab/electronics';
import type { HelpSection } from './component-information';

const LED_COLOUR_LABELS: Readonly<Record<string, string>> = {
  red: 'красный',
  orange: 'оранжевый',
  yellow: 'жёлтый',
  green: 'зелёный',
  blue: 'синий',
  white: 'белый',
};

export function componentHelpSections(
  kind: ComponentKind,
  catalogDescription: string,
  variantId?: string,
  options?: { readonly ledColour?: string },
): readonly HelpSection[] {
  const principle: Partial<Record<ComponentKind, string>> = {
    source: 'Источник поддерживает заданную разность потенциалов между своими выводами.',
    resistor: 'Резистор ограничивает ток; ток зависит от напряжения и сопротивления цепи.',
    potentiometer: 'Движок делит полное сопротивление на два связанных плеча.',
    photoresistor: 'Сопротивление чувствительного элемента изменяется вместе с освещённостью.',
    led: 'Светодиод проводит ток в прямом направлении и преобразует часть мощности в свет.',
    diode: 'Диод преимущественно проводит ток в одном направлении.',
    button: 'Кнопка временно соединяет контакты, пока пользователь её удерживает.',
    switch: 'Переключатель соединяет общий контакт с выбранным выводом.',
    piezo: 'Пьезоэлемент преобразует переменный электрический сигнал в механические колебания.',
    transistor: 'Транзистор управляет током одной цепи с помощью сигнала в управляющем выводе.',
    lamp: 'Нить лампы нагревается электрической мощностью и излучает свет.',
    breadboard: 'Группы отверстий внутри макетной платы электрически соединены.',
  };
  if (kind === 'diode') {
    const isDo41 = variantId === 'diode-do41';
    return [
      {
        id: 'description',
        title: 'Описание',
        text: isDo41
          ? 'DO-41 — выпрямительный диод для более высокого тока и обратного напряжения.'
          : 'DO-35 — малосигнальный диод для быстрых переключений и небольшого тока.',
      },
      {
        id: 'principle',
        title: 'Принцип работы',
        text: 'При достаточном прямом напряжении диод открыт и проводит ток. При обратном включении он закрыт, пока напряжение не превысит допустимый предел.',
      },
      {
        id: 'usage',
        title: 'Чем отличаются варианты',
        text: 'DO-35: до 200 мА и 100 В — сигнальные и переключательные цепи. DO-41: до 1 А и 1000 В — выпрямление и силовые цепи. Эти пределы и разные прямые характеристики используются в расчёте.',
      },
    ];
  }
  if (kind === 'led') {
    const colour = options?.ledColour ?? 'red';
    const profile = ordinaryLedProfile(colour);
    const forwardAtNominal =
      profile.kneeVoltage + profile.dynamicResistanceOhm * profile.nominalCurrentAmp;
    return [
      {
        id: 'description',
        title: 'Что имитируется',
        text: `Типовой ${LED_COLOUR_LABELS[colour] ?? colour} индикаторный светодиод диаметром 5 мм. Это расчётный профиль класса компонентов, а не скрытый артикул конкретного производителя.`,
      },
      {
        id: 'principle',
        title: 'Рабочая точка',
        text: `При номинальном токе 20 мА модель имеет прямое напряжение около ${forwardAtNominal.toFixed(2)} В. Это напряжение на самом светодиоде, а не требуемое напряжение батареи: лишнее напряжение должен принять последовательный резистор.`,
      },
      {
        id: 'usage',
        title: 'Как подобрать резистор',
        text: 'Анод подключают к плюсу через резистор, катод — к минусу. Оценка: R = (напряжение источника − прямое напряжение светодиода) / выбранный ток. Для учебной схемы обычно выбирайте 5–15 мА, затем проверяйте фактический ток во вкладке i.',
      },
      {
        id: 'safety',
        title: 'Пределы модели',
        text: 'Номинальный ток — 20 мА, разрушительный режим типового 5-мм профиля начинается при 120 мА, допустимое обратное напряжение — 5 В. Цвет изменяет прямое напряжение, поэтому один резистор не даёт одинаковый ток со всеми цветами.',
      },
    ];
  }
  if (kind === 'potentiometer') {
    return [
      {
        id: 'description',
        title: 'Описание',
        text: 'Потенциометр — регулируемый делитель напряжения с двумя крайними выводами и подвижным выводом-движком.',
      },
      {
        id: 'principle',
        title: 'Что меняет ручка',
        text: 'Полное сопротивление между крайними выводами постоянно. Поворот ручки увеличивает одно плечо между движком и краем и на столько же уменьшает другое.',
      },
      {
        id: 'usage',
        title: 'Как использовать',
        text: 'Для делителя подключите оба крайних вывода, а сигнал снимайте с движка. Как регулируемый резистор используйте движок и один крайний вывод — второй край тогда может оставаться свободным.',
      },
    ];
  }
  if (kind === 'transistor' && variantId === 'transistor-npn') {
    return [
      {
        id: 'description',
        title: 'Что имитируется',
        text: 'Типовой маломощный NPN-транзистор в корпусе TO-92. Это расчётный профиль класса компонентов, а не скрытый артикул конкретного производителя.',
      },
      {
        id: 'principle',
        title: 'Рабочие области',
        text: 'В отсечке ток коллектора почти отсутствует. В активной области ток коллектора управляется током базы. В насыщении транзистор работает как замкнутый ключ с небольшим напряжением коллектор–эмиттер.',
      },
      {
        id: 'usage',
        title: 'NPN как ключ',
        text: 'Эмиттер обычно соединяют с минусом питания, нагрузку ставят между плюсом и коллектором, а базу подключают к управляющему сигналу через ограничивающий резистор. Вкладка I показывает область, токи B/C/E и мощность.',
      },
      {
        id: 'safety',
        title: 'Пределы модели',
        text: 'Профиль учитывает конечный коэффициент усиления, насыщение, Early effect, ток коллектора и рассеиваемую мощность. Превышение предела не блокирует расчёт: компонент получает локальное разрушительное состояние.',
      },
    ];
  }
  if (kind === 'source' && variantId?.startsWith('battery')) {
    const holder = /^battery-holder-aa-(\d+)$/.exec(variantId);
    const voltage = holder
      ? Number(holder[1]) * 1.5
      : Number(/battery-(\d+(?:\.\d+)?)v/.exec(variantId)?.[1]);
    return [
      {
        id: 'description',
        title: 'Описание',
        text: holder
          ? `Батарейный отсек соединяет ${holder[1]} элементов AA последовательно и даёт номинально ${voltage} В.`
          : `Батарея — фиксированный источник постоянного напряжения${Number.isFinite(voltage) ? ` ${voltage} В` : ''}.`,
      },
      {
        id: 'principle',
        title: 'Что происходит под нагрузкой',
        text: 'Номинальное напряжение задаётся вариантом и не регулируется. Из-за внутреннего сопротивления напряжение на клеммах проседает под большим током, а источник нагревается.',
      },
      {
        id: 'safety',
        title: 'Перегрузка',
        text: 'Короткое замыкание или слишком малая нагрузка вызывает большой ток. Вкладка I показывает нагрузку по току, просадку напряжения и мощность нагрева источника.',
      },
    ];
  }
  const sections: HelpSection[] = [
    { id: 'description', title: 'Описание', text: catalogDescription },
  ];
  if (principle[kind]) {
    sections.push({ id: 'principle', title: 'Принцип работы', text: principle[kind] as string });
  }
  sections.push({
    id: 'connection',
    title: 'Подключение',
    text: 'Подключайте провода к обозначенным выводам компонента. Точные состояния выводов показаны во вкладке технической информации.',
  });
  return sections;
}
